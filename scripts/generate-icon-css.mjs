import { readdir, readFile, writeFile } from "node:fs/promises";
import { extname, join, resolve } from "node:path";

const root = resolve(process.cwd());
const sourceRoot = join(root, "src");
const packageCss = join(root, "node_modules/@phosphor-icons/web/src/regular/style.css");
const output = join(sourceRoot, "styles/icons.css");
const sourceExtensions = new Set([".astro", ".ts", ".js", ".mjs"]);

async function collectFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return collectFiles(path);
    return sourceExtensions.has(extname(entry.name)) ? [path] : [];
  }));
  return nested.flat();
}

const [css, files] = await Promise.all([readFile(packageCss, "utf8"), collectFiles(sourceRoot)]);
const source = (await Promise.all(files.map((file) => readFile(file, "utf8")))).join("\n");
const blocks = [...css.matchAll(/\.ph\.ph-([a-z0-9-]+):before\s*\{[^}]+\}/g)];
const selected = blocks.filter((match) => {
  const name = match[1];
  return source.includes(`ph-${name}`) || new RegExp(`["'\x60]${name}["'\x60]`).test(source);
});

const base = `/* Generated by scripts/generate-icon-css.mjs. Do not edit directly. */
@font-face {
  font-family: "Phosphor";
  src: url("@phosphor-icons/web/regular/Phosphor.woff2") format("woff2");
  font-weight: normal;
  font-style: normal;
  font-display: block;
}

.ph {
  font-family: "Phosphor" !important;
  speak: never;
  font-style: normal;
  font-weight: normal;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  letter-spacing: 0;
  font-feature-settings: "liga";
  font-variant-ligatures: discretionary-ligatures;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}
`;

await writeFile(output, `${base}\n${selected.map((match) => match[0]).join("\n\n")}\n`);
console.log(`Generated ${selected.length} Phosphor icon rules in ${output}`);
